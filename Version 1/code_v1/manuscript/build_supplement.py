"""Build the supplementary document (.docx)."""
import json
import sys
from pathlib import Path
import numpy as np
import pandas as pd
from docx_utils import Doc
from results_loader import load, f3, ci, hrow, DEEP
from build_paper import TITLE

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / "figures"
sys.path.insert(0, str(ROOT / "src"))


def build(out: Path, anonymous=True):
    from beed import models, features
    R = load()
    D = Doc(line_spacing=1.5)
    D.fig_prefix = "S"; D.tab_prefix = "S"
    D.title("Supplementary Material")
    D.para(TITLE, center=True, italic=True)
    D.para("This document contains extended tables, additional figures, hyper-parameter grids and full per-fold results. "
           "Supplementary File S1 is the accompanying code-and-results archive (run_all.py, src/, results/, figures/, "
           "analysis.ipynb). All values were generated by that code.", align="justify")

    D.h1("S1 Hyper-parameter grids and selected values")
    rows = []
    for name, (est, grid) in models.get_models().items():
        fixed = {k: v for k, v in est.get_params().items() if k in ("n_estimators", "subsample", "colsample_bytree", "max_iter", "kernel")}
        rows.append([name, "; ".join(f"{k.split('__')[-1]} ∈ {v}" for k, v in grid.items()) or "–",
                     "; ".join(f"{k}={v}" for k, v in fixed.items()) or "–"])
    rows += [[m, "– (fixed architecture)", "AdamW lr 0.002, weight decay 1e-4, batch 128, ≤60 epochs, patience 8"] for m in DEEP]
    D.table("Hyper-parameter search grids (inner three-fold CV, macro-F1)", ["Model", "Grid", "Fixed settings"], rows, font_size=8.5)
    p = R["params"]
    p = p[(p.model != "Majority")]
    rows = [[r.task, r.protocol, r.features, r.model, r.best_params.replace('"', "")] for r in p.itertuples()]
    D.table("Hyper-parameters selected on the development set for each hold-out run", ["Task", "Protocol", "Features", "Model", "Selected"], rows, font_size=7.5)

    D.h1("S2 Extended hold-out results")
    h = R["holdout"]
    rows = []
    for prot in ["random", "blocked"]:
        g = h[(h.task == "4class") & (h.protocol == prot)].sort_values(["features", "macro_f1"], ascending=[True, False])
        for r in g.itertuples():
            rows.append([prot, r.features, r.model, f3(r.accuracy), f3(r.macro_f1), f3(r.kappa), f3(r.auc), f3(r.brier), f3(r.ece), f"{r.fit_seconds:.1f}"])
    D.table("Four-class hold-out results for all models and feature sets",
            ["Protocol", "Features", "Model", "Accuracy", "Macro-F1", "Kappa", "AUC", "Brier", "ECE", "Fit (s)"], rows, font_size=7.5,
            note="Fit time includes nested hyper-parameter search on 8 CPU cores.")
    rows = []
    for prot in ["random", "blocked"]:
        g = h[(h.task == "4class") & (h.protocol == prot) & (h.features.isin(["raw", "raw+eng"])) & (h.model != "Majority")]
        for r in g.sort_values("macro_f1", ascending=False).itertuples():
            rows.append([prot, r.features, r.model, f3(r.macro_f1), ci(r.f1_ci_lo, r.f1_ci_hi), ci(r.f1_cci_lo, r.f1_cci_hi),
                         f3(r.accuracy), ci(r.acc_ci_lo, r.acc_ci_hi), ci(r.acc_cci_lo, r.acc_cci_hi)])
    D.table("Row-level versus cluster bootstrap 95% confidence intervals (four-class)",
            ["Protocol", "Features", "Model", "Macro-F1", "Row CI", "Cluster CI", "Accuracy", "Row CI", "Cluster CI"], rows, font_size=7.5,
            note="Row CI: independent resampling of test rows. Cluster CI: class-stratified resampling of Bonn segments (class 0) "
                 "and 50-row chunks (classes 1–3), which respects autocorrelation and is the primary interval in the paper.")
    pc = R["perclass"]
    rows = []
    for task in ["4class", "3class"]:
        for prot in ["random", "blocked"]:
            b = R["best"][(task, prot)]
            g = pc[(pc.task == task) & (pc.protocol == prot) & (pc.model == b.model) & (pc.features == b.features)]
            for r in g.itertuples():
                rows.append([task, prot, f"{b.model} ({b.features})", r._1 if hasattr(r, "_1") else r[1], f3(r.precision), f3(r.recall), f3(r.f1), int(r.support)])
    D.table("Per-class precision, recall and F1 of the best hold-out models",
            ["Task", "Protocol", "Model", "Class", "Precision", "Recall", "F1", "Support"], rows, font_size=8)
    rows = []
    for task in ["binary", "3class"]:
        for prot in ["random", "blocked"]:
            g = h[(h.task == task) & (h.protocol == prot)].sort_values("macro_f1", ascending=False)
            for r in g.itertuples():
                rows.append([task, prot, r.features, r.model, f3(r.accuracy), f3(r.macro_f1), ci(r.f1_cci_lo, r.f1_cci_hi), f3(r.kappa), f3(r.auc), f3(r.ece)])
    D.table("Binary and three-class hold-out results",
            ["Task", "Protocol", "Features", "Model", "Accuracy", "Macro-F1", "Cluster CI", "Kappa", "AUC", "ECE"], rows, font_size=7.5)
    if R["stumps"] is not None:
        rows = [[r.protocol, r.feature, f"{r.threshold:.3f}", f3(r.accuracy), f3(r.macro_f1)] for r in R["stumps"].itertuples()]
        D.table("Single-feature, single-threshold classifiers for healthy versus seizure",
                ["Protocol", "Feature", "Threshold", "Accuracy", "Macro-F1"], rows, font_size=9,
                note="Depth-1 decision tree trained on the development set; evaluated on the hold-out test set.")

    D.h1("S3 Cross-validation, statistics and leakage diagnostics")
    cv = R["cvfold"]
    for task in ["4class", "3class"]:
        for prot in ["random", "blocked"]:
            t = cv[(cv.task == task) & (cv.protocol == prot)].pivot(index="fold", columns="model", values="macro_f1")
            cols = list(t.columns)
            rows = [[str(int(i) + 1)] + [f3(v) for v in t.loc[i]] for i in t.index]
            rows.append(["Mean"] + [f3(t[cname].mean()) for cname in cols])
            D.table(f"Per-fold macro-F1, nested 5 × 2 CV, {task}, {prot} protocol", ["Fold"] + cols, rows, font_size=7.5)
    tt = R["ttest"]
    rows = [[r.task, r.protocol, r.best, r.other, f3(r.best_mean_f1), f3(r.other_mean_f1), f"{r.t:.2f}", f"{r.p:.4f}", f"{r.p_holm:.4f}"] for r in tt.itertuples()]
    D.table("Corrected resampled t-tests against the best model (all settings)",
            ["Task", "Protocol", "Best", "Other", "F1 best", "F1 other", "t", "p", "p (Holm)"], rows, font_size=7.5)
    fr = R["friedman"]
    rows = []
    for _, r in fr.iterrows():
        ranks = {c[5:]: r[c] for c in fr.columns if c.startswith("rank_") and pd.notna(r[c])}
        rows.append([r.task, r.protocol, f"{r.friedman_chi2:.2f}", f"{r.friedman_p:.2e}", f"{r.critical_difference:.2f}",
                     "; ".join(f"{k} {v:.2f}" for k, v in sorted(ranks.items(), key=lambda x: x[1]))])
    D.table("Friedman tests and mean ranks (Nemenyi critical difference)", ["Task", "Protocol", "χ²", "p", "CD", "Mean ranks"], rows, font_size=7.5,
            note="Folds of repeated CV are not independent, so Friedman/Nemenyi results are indicative only.")
    nn = R["nn"]
    rows = [[str(k), f3(r.nn_same_class), f3(r.nn_within_1_row), f3(r.nn_within_5_rows), f"{r.median_row_distance:.0f}"] for k, r in nn.iterrows()]
    D.table("Nearest training neighbour of random-split test rows", ["Class", "Same class", "Within 1 row", "Within 5 rows", "Median distance (rows)"], rows, font_size=9)
    bl = R["block"]
    rows = [[r.model, str(r.block_size), str(r.gap), f"{f3(r.f1)} ± {f3(r.sd)}", f3(r.acc)] for r in bl.itertuples()]
    D.table("Block-size curve: five-fold CV macro-F1 by contiguous block size", ["Model", "Block size", "Purge gap", "Macro-F1", "Accuracy"], rows, font_size=8,
            note="Block size 5 with a 50-row purge leaves very little training data for classes 1–3; this setting is not interpretable.")
    w = R["windowed"]
    rows = [[m, str(int(r.n_windows)), f"{r.window_s:.2f}", f3(r.accuracy), f3(r.macro_f1), f3(r.kappa)] for m, r in w.iterrows()]
    D.table("Windowed multichannel analysis of classes 1–3 (leave-one-block-out)", ["Model", "Windows", "Window (s)", "Accuracy", "Macro-F1", "Kappa"], rows, font_size=9,
            note="Features: per-channel log Welch band power (0.5–4, 4–8, 8–13, 13–30, 30–70 Hz) and log line length (96 features).")

    D.h1("S4 Ablation and feature definitions")
    ab = R["ablation"]
    rows = [[r.task, r.protocol, r.config, str(r.n_features), f"{f3(r.cv_macro_f1_mean)} ± {f3(r.cv_macro_f1_sd)}", f3(r.test_macro_f1)] for r in ab.itertuples()]
    D.table("Feature-group ablation with LightGBM", ["Task", "Protocol", "Configuration", "Features", "CV macro-F1", "Test macro-F1"], rows, font_size=7.5)
    import numpy as _np
    eng = features.engineered(_np.zeros((2, 16)) + _np.arange(16))
    grp = {}
    for col in eng.columns:
        grp.setdefault(features.group_of(col), []).append(col)
    rows = [[g, str(len(cs)), ", ".join(cs)] for g, cs in grp.items()]
    D.table("Engineered feature names by group", ["Group", "Count", "Features"], rows, font_size=8)
    sh = R["shap"][("3class", "blocked")].head(20)
    rows = [[i, *[f"{v:.3f}" for v in r.values]] for i, r in sh.iterrows()]
    D.table("Top-20 features by mean |SHAP|, three-class task, blocked protocol", ["Feature"] + list(sh.columns), rows, font_size=8)

    D.h1("S5 Additional figures")
    D.figure(FIG / "fig_examples.png", "Example rows per class and class-2 rows displayed as 16 traces",
             "(a) One row of each class plotted against column index. (b) The first 512 rows of class 2 plotted as 16 channels over "
             "time (2 s at 256 Hz), showing smooth evolution across rows, in contrast with class 0.")
    D.figure(FIG / "fig_psd.png", "Spectral content of the BEED classes",
             "(a) Welch power spectral density along rows for classes 1–3 (assuming 256 Hz), averaged over channels. (b) Relative "
             "power in the eight non-DC bins of the 16-value within-row FFT for all classes.")
    D.figure(FIG / "fig_tsne.png", "t-SNE embedding of engineered features",
             "600 randomly selected rows per class; class 0 forms a separate cluster, consistent with its different source.")
    D.figure(FIG / "fig_calibration.png", "Reliability diagrams on the four-class hold-out test sets",
             "Observed accuracy versus mean confidence in ten bins (bins with fewer than ten samples omitted); legend gives ECE.")
    D.figure(FIG / "fig_ranks.png", "Mean ranks of models across repeated cross-validation folds",
             "Error bars span the Nemenyi critical difference; models whose bars overlap are not significantly different.")
    D.figure(FIG / "fig_ablation.png", "Feature-group ablation under random and blocked protocols",
             "LightGBM with fixed hyper-parameters; five-fold CV on the development set (mean ± SD).")
    D.figure(FIG / "fig_roc_pr.png", "One-vs-rest ROC and precision–recall curves of the best four-class models",
             "Left: random protocol; right: blocked protocol. AUC, area under the curve; AP, average precision.")
    D.figure(FIG / "fig_shap_beeswarm_GS.png", "SHAP beeswarm for the generalised-seizure output (three-class, blocked)",
             "Each point is one test row; colour encodes feature value (red high, blue low).", width_in=5.0)
    D.figure(FIG / "fig_pipeline.png", "Overview of the audit and leakage-aware evaluation pipeline",
             "Rows are grouped by provenance (Bonn segment for class 0; contiguous 200-row blocks for classes 1–3) before any split. "
             "Both protocols use the same features, models, nested tuning and metrics.")
    D.figure(FIG / "fig_holdout_bars.png", "Four-class hold-out macro-F1 under random and blocked protocols",
             "Classical models on raw+engineered features; deep models on raw values. Error bars: 95% cluster-bootstrap CIs. "
             "Hatched bars: blocked protocol. The same values are tabulated in Table 3 of the paper and Supplementary Table S2.")
    D.save(out)


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT
    build(out / "BEED_supplementary.docx")
