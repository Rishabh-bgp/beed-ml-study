"""Draft cover letter / author declaration (Section 22 of the guidelines)."""
import sys
from pathlib import Path
from docx_utils import Doc
from build_paper import TITLE, authors


def build(out: Path):
    D = Doc(line_spacing=1.08, space_after=4)
    D.para("[Date]", align="left")
    D.para("To the Organising/Editorial Committee\nNIELIT Bio-AI Conclave 2026\nNIELIT Guwahati, India", align="left")
    D.para("**Subject: Submission of a full research paper to Track 5 (Digital Life Sciences, Health, Agriculture & Biodiversity)**", align="left")
    D.para("Dear Members of the Committee,", align="left")
    D.para(f"On behalf of all authors, I submit the full research paper entitled “{TITLE}” for consideration at NIELIT Bio-AI "
           "Conclave 2026 under Track 5 (healthcare artificial intelligence). The manuscript audits a widely used public EEG "
           "epilepsy dataset, shows that its healthy class is copied from an older benchmark and that its seizure classes are "
           "temporally autocorrelated, and provides a leakage-aware, statistically grounded benchmark of lightweight seizure-type "
           "classifiers with a fully reproducible pipeline. Secondary area of relevance: Track 3 (Computational Biology, Bioinformatics & Research Infrastructure; reproducibility).")
    D.para("In accordance with Section 22 of the submission guidelines, I confirm that:")
    D.bullets([
        "the manuscript is original and has not been published previously in substantially the same form;",
        "the manuscript is not simultaneously submitted to, or under consideration by, another conference, journal or publication venue;",
        "all listed authors have reviewed and approved the final manuscript;",
        "all authors have consented to the submission and agree to participate in the review and publication process;",
        "any actual or potential conflicts of interest have been disclosed in the manuscript (the authors declare none) [authors to confirm];",
        "no third-party copyrighted material requiring permission is included; all figures were generated by the authors from public data, and all data sources are cited;",
        "at least one author will complete the required BioAI Conclave 2026 author registration if the manuscript is accepted;",
        "the use of AI-assisted technologies is disclosed in the manuscript’s declaration [authors to finalise].",
    ])
    D.para("The submission comprises the manuscript (DOCX and identical PDF), the supplementary document (DOCX and identical PDF) "
           "and a supplementary code-and-results archive. The review copy has been anonymised for double-blind review.")
    D.para(authors()["cover_corresponding"], align="left")
    D.para("Yours sincerely,\n[Signature]\n[Author Name], on behalf of all authors (co-authors: [Co-author Name], [Supervisor Name])", align="left")
    D.save(out, title="Cover letter")


if __name__ == "__main__":
    build(Path(sys.argv[1]) / "cover_letter.docx")
